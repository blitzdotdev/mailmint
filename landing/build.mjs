#!/usr/bin/env node
// Builds Fig 1 of the landing page (landing/figure.mjs, drawn with the anatomy kit in landing/kit)
// into a committed module, so the Worker ships plain SVG and needs no build step of its own:
//
//   worker/src/ui/landing-figure.ts   ← landing/figure.mjs + landing/kit/*.mjs
//
//   node landing/build.mjs           # regenerate
//   node landing/build.mjs --check   # fail if it is stale (run by `npm test`)
//
// Like scripts/build.mjs, the output records a hash of its inputs.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const OUT = "worker/src/ui/landing-figure.ts";
const INPUTS = ["landing/build.mjs", "landing/figure.mjs", "landing/kit/iso-kit.mjs", "landing/kit/lathe.mjs"];

const h = createHash("sha256");
for (const f of INPUTS) h.update(f).update("\0").update(readFileSync(join(root, f), "utf8")).update("\0");
const stamp = `// inputs-sha256: ${h.digest("hex").slice(0, 16)}\n`;

let current = "";
try {
  current = readFileSync(join(root, OUT), "utf8");
} catch {}
if (current.includes(stamp)) process.exit(0);
if (check) {
  console.error(`stale: ${OUT} (run: node landing/build.mjs)`);
  process.exit(1);
}

const { ISO_CSS } = await import("./kit/iso-kit.mjs");
const { buildFigure, FIGURE_CSS } = await import("./figure.mjs");
const { svg, data } = buildFigure();
const body =
  `/** Fig 1: the static drawing (it reads with JavaScript off). */\n` +
  `export const FIGURE_SVG = ${JSON.stringify(svg)};\n\n` +
  `/** What landing.client.js needs to move it: screen vectors per world unit, travel distances, the cable's path. */\n` +
  `export const FIGURE_DATA = ${JSON.stringify(data)};\n\n` +
  `/** The anatomy kit's styles (MIT, landing/kit/LICENSE) and the figure's own. */\n` +
  `export const FIGURE_CSS = ${JSON.stringify(ISO_CSS + FIGURE_CSS)};\n`;
writeFileSync(
  join(root, OUT),
  "// GENERATED by landing/build.mjs — edit landing/figure.mjs, then run `node landing/build.mjs`.\n" + stamp + body,
);
console.log(`wrote ${OUT} (${(svg.length / 1024).toFixed(0)} KB of SVG)`);
